#!/usr/bin/env python3
"""
Assemble a ready-to-open Arduino sketch folder for the door guard.

  python tools/arduino_bundle.py              -> build/arduino/door_guard_web/
  python tools/arduino_bundle.py OUT_DIR

The Arduino IDE compiles every .c/.cpp next to the .ino, so this copies the
library, the generated code and the example into one flat folder, and turns
the model and the viewer into C arrays (the ESP32 keeps them in flash).
Only needs Python; no PyYAML or PyTorch.
"""
import gzip
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "python"))


def embed_model(bin_path, out_path):
    from tiny_langgraph.toolchain.train import embed
    embed(bin_path, out_path, "door_guard_model")


def embed_viewer(html_path, out_path):
    raw = open(html_path, "rb").read()
    gz = gzip.compress(raw, compresslevel=9, mtime=0)
    lines = ["/* Generated by tools/arduino_bundle.py from viewer/index.html. Do not edit. */",
             "#pragma once", "#include <stdint.h>", "",
             f"#define WEB_VIEWER_GZ_LEN {len(gz)}u   /* {len(raw)} bytes before gzip */", "",
             "static const uint8_t WEB_VIEWER_GZ[] = {"]
    for i in range(0, len(gz), 20):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
    lines += ["};", ""]
    open(out_path, "w").write("\n".join(lines))
    return len(raw), len(gz)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "build", "arduino", "door_guard_web")
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)

    dg = os.path.join(ROOT, "examples", "door_guard")
    sources = [
        os.path.join(ROOT, "ports", "arduino", "door_guard_web", "door_guard_web.ino"),
        os.path.join(ROOT, "ports", "arduino", "door_guard_web", "door_guard_main.cpp"),
        os.path.join(ROOT, "ports", "arduino", "door_guard_web", "config.h"),
    ]
    for d in ("core", "lm", os.path.join("examples", "door_guard", "generated")):
        full = os.path.join(ROOT, d)
        sources += [os.path.join(full, f) for f in sorted(os.listdir(full)) if f.endswith((".c", ".h"))]
    for name in ("agent", "scenarios"):
        sources += [os.path.join(dg, name + ".c"), os.path.join(dg, name + ".h")]

    for src in sources:
        shutil.copy(src, out)
    embed_model(os.path.join(dg, "model", "door_guard.bin"), os.path.join(out, "door_guard_model.h"))
    raw, gz = embed_viewer(os.path.join(ROOT, "viewer", "index.html"), os.path.join(out, "web_viewer.h"))

    print(f"sketch ready: {os.path.relpath(out, os.getcwd())}")
    print(f"  {len(sources)} source files, model, viewer ({raw:,} bytes -> {gz:,} gzipped)")
    print("  open door_guard_web.ino in the Arduino IDE, edit config.h, upload")
    return 0


if __name__ == "__main__":
    sys.exit(main())
