"""Write the C for a compiled Python agent:

  <name>_schema.h/.c   tokens, encode/decode, the planner's tool table, situations  (toolchain/codegen.py)
  <name>_rules.c       your conditions and @rules function, converted (no hardware: also used by tests)
  <name>_agent.h/.c    the state struct, your nodes, routes and tools, the prebuilt nodes, the graph
"""
from __future__ import annotations

import os

from . import boards
from . import prebuilt as _pb
from .toolchain import codegen
from .transpile import Converter, FuncInfo, _c_str


def _out_dir_files(out_dir, files: dict[str, str]):
    os.makedirs(out_dir, exist_ok=True)
    paths = []
    for name, text in files.items():
        path = os.path.join(out_dir, name)
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        paths.append(path)
    return paths


def generate(app, out_dir: str, source: str) -> list[str]:
    schema = app.schema
    if schema is None:
        raise ValueError("C generation needs an agent with tools (prebuilt.Act)")
    n = codegen._Names(schema)
    P, p = n.P, n.p
    conv = Converter(app, n)
    conv.collect()
    banner = f"/* Generated by tiny-langgraph from {source}. Do not edit: change the Python and rebuild. */\n"

    # ---------------- pure functions -> <name>_rules.c ----------------
    pure = [i for i in conv.funcs.values() if i.role in ("fact", "pure", "rules")]
    pure_c = [conv.convert(i) for i in pure]          # converts first so return types are known
    protos = ["/* ---- your conditions and rules, converted from Python ---- */"]
    protos += [conv.signature(i) + ";" for i in pure]
    model_c = []                                      # catalog models' pure functions (e.g. a Tree)
    for node, c in app.classifiers.items():
        proto, code = c.model.c_rules(node, n)
        protos += proto
        model_c += code
    protos.append("")
    fact_infos = {i.name: i for i in pure if i.role == "fact"}

    codegen.generate(schema, out_dir, source,
                     fact_call=lambda name: f"{conv.cname(fact_infos[name])}(in, th)",
                     extra_h=protos)
    rules_c = [banner, f'#include "{p}_schema.h"', "", _HELPERS] + _tables(conv, "rules") + pure_c + model_c

    # ---------------- the agent ----------------
    st = app.state_schema
    ids = {name: i for i, name in enumerate(app.names)}

    def node_id(i):
        return "TLG_END" if i < 0 else f"{P}_NODE_{app.names[i].upper()}"

    # user nodes, routes, tools, helpers
    user_c = []
    for i in conv.funcs.values():
        if i.role in ("node", "tool", "helper"):
            user_c.append(conv.convert(i))
    route_fns = {}
    for k, (kind, *rest) in enumerate(app.next):
        if kind == "route":
            fn, mapping, targets = rest
            if isinstance(fn, _pb.PrebuiltRoute):
                route_fns[k] = _prebuilt_route(fn, mapping, app.names[k], p, node_id)
            else:
                info = FuncInfo(fn, "route")
                info.cname_override = f"route_{app.names[k]}"
                user_c.append(conv.convert(info, route_map=mapping))
                route_fns[k] = None

    includes = list(dict.fromkeys(i for c in app.classifiers.values() for i in c.model.c_includes()))
    includes.append("tlg_mcp.h")                     # every board is an MCP server (status; + served contracts)
    h = [banner, f"#ifndef {P}_AGENT_H", f"#define {P}_AGENT_H", "",
         f'#include "{p}_schema.h"', '#include "tlg.h"', '#include "tlg_agent.h"']
    h += [f'#include "{i}"' for i in includes] + ["",
         '#ifdef __cplusplus\nextern "C" {\n#endif', "",
         "enum {"] + [f"    {P}_NODE_{name.upper()}," for name in app.names] + [f"    {P}_N_NODES", "};", ""]
    h += ["/* The whole state: what the agent observes and concludes, its memory, and the bookkeeping",
          "   for the prebuilt nodes. Keep one alive between runs: Int fields are its memory. */",
          "typedef struct {",
          f"    {p}_inputs_t in;       /* Choice fields */",
          f"    {p}_think_t  th;       /* Think fields */"]
    h += [f"    int32_t {f.name};" for f in st.ints()]
    h += [f"    {c.model.c_memory()} m_{node};   /* {node}: {c.model!r}'s memory */"
          for node, c in app.classifiers.items() if c.model.c_memory()]
    h += ["    tlg_agent_t agent;", f"}} {p}_state_t;", "",
          f"extern const tlg_node_t {p}_nodes[{P}_N_NODES];", "",
          "/* Once at startup: default values for every field. */",
          f"void {p}_state_init({p}_state_t *s);",
          "/* Before every run: clears the per-run bookkeeping (memory stays). */",
          f"void {p}_begin({p}_state_t *s);",
          "/* Fills a graph for this agent; tracing is on when s->agent.tracer is set. */",
          f"void {p}_graph(tlg_graph_t *g, {p}_state_t *s);",
          "/* Once at startup: set up the pins of every driver the agent uses. */",
          f"void {p}_drivers_init(void);",
          *([f"/* The mailbox's network state: the sketch moves its messages over the radio. */",
             f"tlg_net_t *{p}_net(void);"] if app.mailbox else []),
          "/* The data log (one CSV line per run): column names, and this run's values: every Choice/Score",
          "   field, then the plan carried out (tools joined by +, \"nothing\", or - if nothing was checked).",
          "   Both return what snprintf returns. */",
          f"int {p}_log_header(char *buf, size_t size);",
          f"int {p}_log_row(const {p}_state_t *s, char *buf, size_t size);",
          "/* For the MCP endpoint: this run's fields and plan as a JSON object (or -1 if it doesn't fit),",
          "   and the contracts this board serves. */",
          f"int {p}_status_json(const {p}_state_t *s, char *buf, size_t size);",
          f"const tlg_mcp_contract_t *{p}_mcp_list(int *n);", "",
          "#define " + f"{P}_MAX_STEPS {app.max_steps}", "",
          '#ifdef __cplusplus\n}\n#endif', "", f"#endif /* {P}_AGENT_H */", ""]

    c = [banner, f'#include "{p}_agent.h"', '#include "tlg_drivers.h"']
    c += ['#include "tlg_lm.h"'] if app.uses_model else []
    c += ["", "#include <stdio.h>", "#include <string.h>", "", _HELPERS]
    c += _tables(conv, "agent")
    # value names for notes
    for f in st.inputs() + st.thinks():
        c.append(f"static const char *const V_{f.name.upper()}[] = {{ " + ", ".join(f'"{v}"' for v in f.values) + " };")
    c.append("")
    for node, cl in app.classifiers.items():
        c += cl.model.c_tables(node, n)
    # drivers
    custom = []
    for name, obj in conv.drivers.values():
        if obj.c_struct:
            init = ", ".join(f".{k} = {_c_val(boards.any_gpio(v) if k == 'pin' else v)}" for k, v in obj.c_init().items())
            c.append(f"static const {obj.c_struct} drv_{name} = {{ {init} }};")
        if obj.c_header is None:
            custom.append(obj)
    for obj in custom:
        c.append(f"/* your C driver {type(obj).__name__}: {', '.join(obj.c_files) or 'functions defined elsewhere'} */")
        for m, (params, ret) in obj.c_methods().items():
            args = ", ".join({"int": "int32_t", "bool": "bool", "str": "const char *"}[t] + " " + pn
                             for pn, t in params) or "void"
            rt = {"None": "void", "int": "int32_t", "bool": "bool"}[ret]
            c.append(f"{rt} {obj.c_prefix}_{m}({args});")
        if hasattr(obj, "init") and callable(getattr(obj, "init")):
            c.append(f"void {obj.c_prefix}_init(void);")
    c.append("")
    c += _net_code(app, n, P, p)
    c += [f"static bool tool_{t.name}({p}_state_t *s);" for t in app.tools]
    c.append("")
    c += user_c
    for node, cl in app.classifiers.items():         # prebuilt.Classify: ask the model, write the field
        c += [f"/* {node}: {' '.join(cl.question.split()).replace('*/', '* /')} */",
              f"static void classify_{node}(void *st, tlg_run_t *run)", "{", "    (void)run;",
              f"    {p}_state_t *s = st;"]
        c += ["    " + line for line in cl.model.c_step(node, n, conv, cl.field)]
        c += [f'    tlg_agent_say(&s->agent, "{cl.field}=%s", V_{cl.field.upper()}[s->in.{cl.field}]);', "}", ""]
    c += _prebuilt_nodes(app, P, p, st)
    for k, code in route_fns.items():
        if code:
            c.append(code)

    # node table
    c.append(f"const tlg_node_t {p}_nodes[{P}_N_NODES] = {{")
    for k, name in enumerate(app.names):
        a = app.actions[k]
        if isinstance(a, _pb.Classify):
            run = f"classify_{name}"
        elif isinstance(a, _pb.Prebuilt):
            run = f"pre_{a.kind}"
        elif getattr(a, "_tlg_rules", False):
            run = "pre_rules"
        else:
            run = f"node_{a.__name__}"
        kind, *rest = app.next[k]
        if kind == "edge":
            edge = f"TLG_EDGE({node_id(rest[0])})"
        else:
            edge = f"TLG_ROUTE(route_{name}, {', '.join(node_id(t) for t in rest[2])})"
        c.append(f'    [{P}_NODE_{name.upper()}] = {{ "{name}", {run}, {edge} }},')
    c += ["};", ""]

    # state init / begin / graph / drivers
    c.append(f"void {p}_state_init({p}_state_t *s)\n{{")
    c.append("    memset(s, 0, sizeof *s);")
    for f in st.inputs():
        c.append(f"    s->in.{f.name} = {n.val(f.name, f.default)};")
    for f in st.thinks():
        c.append(f"    s->th.{f.name} = {n.val(f.name, f.default)};")
    for f in st.ints():
        c.append(f"    s->{f.name} = {f.default};")
    if app.mailbox:
        c.append(f"    tlg_net_init(&NET, \"{p}\", NET_SERVED, {len(app.mailbox.serves)}, NET_USED, "
                 f"{sum(len(v) for v in app.mailbox.uses.values())}, NET_PEERS, {len(app.mailbox.uses)});")
    for node, cl in app.classifiers.items():
        c += ["    " + line for line in cl.model.c_init(node)]
    c += ["}", ""]
    c.append(f"void {p}_begin({p}_state_t *s)\n{{")
    c.append("    tlg_agent_begin(&s->agent);")
    for f in st.thinks():
        c.append(f"    s->th.{f.name} = {n.val(f.name, f.default)};")
    c += ["}", ""]
    c += [f"void {p}_graph(tlg_graph_t *g, {p}_state_t *s)", "{",
          "    memset(g, 0, sizeof *g);",
          f"    g->nodes = {p}_nodes;", f"    g->n_nodes = {P}_N_NODES;",
          f"    g->start = {node_id(app.start)};", f"    g->max_steps = {P}_MAX_STEPS;",
          "    if (s->agent.tracer) {", "        g->on_step = tlg_trace_on_step;",
          "        g->user = s->agent.tracer;", "    }", "}", ""]
    cols = [f.name for f in st.inputs()]
    c += [f"int {p}_log_header(char *buf, size_t size)", "{",
          f'    return snprintf(buf, size, "{",".join(cols + ["plan"])}");', "}", "",
          f"int {p}_log_row(const {p}_state_t *s, char *buf, size_t size)", "{",
          "    const tlg_agent_t *a = &s->agent;",
          f'    int n = snprintf(buf, size, "{"".join("%s," for _ in cols)}"'
          + "".join(f", V_{f.upper()}[s->in.{f}]" for f in cols) + ");",
          "    if (n < 0 || (size_t)n >= size) return n;",
          "    if (!a->acted_ok || a->plan_len == 0)",
          '        return n + snprintf(buf + n, size - (size_t)n, "%s", a->acted_ok ? "nothing" : "-");',
          "    for (int i = 0; i < a->plan_len; i++) {",
          f'        int w = snprintf(buf + n, size - (size_t)n, "%s%s", i ? "+" : "", {p}_domain.actions[a->plan[i]].name);',
          "        if (w < 0 || (size_t)(n + w) >= size) return n + w;",
          "        n += w;", "    }", "    return n;", "}", ""]
    c += _mcp_code(app, st, p)
    c.append(f"void {p}_drivers_init(void)\n{{")
    for name, obj in conv.drivers.values():
        if obj.c_struct:
            c.append(f"    {obj.c_prefix}_init(&drv_{name});")
    for obj in custom:
        if hasattr(obj, "init") and callable(getattr(obj, "init")):
            c.append(f"    {obj.c_prefix}_init();")
    c += ["}", ""]
    del ids

    files = {f"{p}_rules.c": "\n".join(rules_c), f"{p}_agent.h": "\n".join(h), f"{p}_agent.c": "\n".join(c)}
    paths = _out_dir_files(out_dir, files)
    return [os.path.join(out_dir, f"{p}_schema.h"), os.path.join(out_dir, f"{p}_schema.c")] + paths, conv


def _q(text: str) -> str:
    """A C string literal."""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _mcp_code(app, st, p):
    """The MCP endpoint's view of this agent: its fields as JSON (the status tool; must match
    McpServer._status) and the served contracts' names, values and replies (tools/list)."""
    cols = [f.name for f in st.inputs()]
    fmt = "{" + "".join(f'\\"{f}\\":\\"%s\\",' for f in cols) + '\\"plan\\":\\"'
    out = [f"int {p}_status_json(const {p}_state_t *s, char *buf, size_t size)", "{",
           "    const tlg_agent_t *a = &s->agent;",
           f'    int n = snprintf(buf, size, "{fmt}"' + "".join(f", V_{f.upper()}[s->in.{f}]" for f in cols) + ");",
           "    if (n < 0 || (size_t)n >= size) return -1;",
           "    if (!a->acted_ok || a->plan_len == 0)",
           '        n += snprintf(buf + n, size - (size_t)n, "%s", a->acted_ok ? "nothing" : "-");',
           "    for (int i = 0; a->acted_ok && i < a->plan_len && (size_t)n < size; i++)",
           f'        n += snprintf(buf + n, size - (size_t)n, "%s%s", i ? " " : "", {p}_domain.actions[a->plan[i]].name);',
           "    if ((size_t)n >= size) return -1;",
           '    n += snprintf(buf + n, size - (size_t)n, "\\"}");',
           "    return (size_t)n < size ? n : -1;", "}", ""]
    rows = []
    for c in (app.mailbox.serves if app.mailbox else []):
        C = c.name.upper()
        if c.params:
            out.append(f"static const char *const MP_{C}[] = {{ {', '.join(_q(q) for q in c.params)} }};")
            out.append(f"static const uint8_t MN_{C}[] = {{ {', '.join(str(len(v)) for v in c.params.values())} }};")
            for q, v in c.params.items():
                out.append(f"static const char *const MV_{C}_{q.upper()}[] = {{ {', '.join(_q(x) for x in v)} }};")
            out.append(f"static const char *const *const MVS_{C}[] = {{ {', '.join(f'MV_{C}_{q.upper()}' for q in c.params)} }};")
        out.append(f"static const char *const MR_{C}[] = {{ {', '.join(_q(r) for r in c.replies)} }};")
        tables = f"MP_{C}, MN_{C}, MVS_{C}" if c.params else "NULL, NULL, NULL"
        rows.append(f"{{ {_q(c.name)}, {_q(c.about)}, {len(c.params)}, {tables}, {len(c.replies)}, MR_{C}, "
                    f"0x{c.fingerprint:08x}u }}")
    if rows:
        out += ["static const tlg_mcp_contract_t MCP_CONTRACTS[] = {"] + [f"    {r}," for r in rows] + ["};"]
    out += [f"const tlg_mcp_contract_t *{p}_mcp_list(int *n)", "{", f"    *n = {len(rows)};",
            f"    return {'MCP_CONTRACTS' if rows else 'NULL'};", "}", ""]
    return out


def _net_code(app, n, P, p):
    """The mailbox in C: contract tables, the mailbox node, and what tools call
    (feeder.call(feed, "one") -> p_net_call, mailbox.reply(feed, "done") -> p_net_reply)."""
    mb = app.mailbox
    if not mb:
        return []
    peers = list(mb.uses)
    used = [(peer, c) for peer, cs in mb.uses.items() for c in cs]
    served = ", ".join(f"{{ 0x{c.fingerprint:08x}u, {len(c.params)} }}" for c in mb.serves) or "{ 0, 0 }"
    used_t = ", ".join(f"{{ {peers.index(peer)}, 0x{c.fingerprint:08x}u }}" for peer, c in used) or "{ 0, 0 }"
    names = ", ".join(f'"{peer.name}"' for peer in peers) or '""'
    say = "tlg_agent_say(&s->agent, "
    out = ["/* ---------------- the mailbox: talking to other boards (tiny_langgraph.net) ---------------- */",
           f"/* served: {', '.join(c.name for c in mb.serves) or 'none'}; used: "
           f"{', '.join(f'{peer.name}.{c.name}' for peer, c in used) or 'none'} */",
           f"static const tlg_net_served_t NET_SERVED[] = {{ {served} }};",
           f"static const tlg_net_used_t NET_USED[] = {{ {used_t} }};",
           f"static const char *const NET_PEERS[] = {{ {names} }};",
           "static tlg_net_t NET;", "",
           f"tlg_net_t *{p}_net(void) {{ return &NET; }}", "",
           "/* prebuilt.Mailbox: requests, discovery and replies -> this run's fields */",
           "static void pre_mailbox(void *st, tlg_run_t *run)", "{", "    (void)run;",
           f"    {p}_state_t *s = st;"]
    if mb.serves:
        out += ["    uint8_t v[TLG_NET_PARAMS];", "    char from[TLG_NET_NAME];"]
    for i, c in enumerate(mb.serves):
        args = "".join(f", V_{f'{c.name}_{q}'.upper()}[v[{k}]]" for k, q in enumerate(c.params))
        fmt = ", ".join("%s" for _ in c.params)
        out += [f"    if (tlg_net_take_request(&NET, {i}, v, from)) {{",
                f"        s->in.{c.name}_asked = {n.val(f'{c.name}_asked', 'yes')};"]
        out += [f"        s->in.{c.name}_{q} = v[{k}];" for k, q in enumerate(c.params)]
        out += [f'        {say}"asked by %s: {c.name}({fmt})", from{args});',
                "    } else {", f"        s->in.{c.name}_asked = {n.val(f'{c.name}_asked', 'no')};", "    }"]
    if mb.uses:
        out.append("    uint8_t r;")
    for k, peer in enumerate(peers):
        out += [f"    s->in.{peer.name}_online = tlg_net_online(&NET, {k}) ? "
                f"{n.val(f'{peer.name}_online', 'yes')} : {n.val(f'{peer.name}_online', 'no')};",
                f"    if (!s->in.{peer.name}_online) {say}\"{peer.name}: offline\");"]
    for u, (peer, c) in enumerate(used):
        out += [f"    r = tlg_net_take_reply(&NET, {u});",
                f"    s->in.{c.name}_reply = r;",
                f'    if (r) {say}"reply from {peer.name}: {c.name} -> %s", V_{c.name.upper()}_REPLY[r]);']
    out += ["}", ""]
    if mb.uses:
        calls = ", ".join(f'"{peer.name}.{c.name}"' for peer, c in used)
        out += [f"static const char *const NET_CALLS[] = {{ {calls} }};",
                "/* a tool calls another board: feeder.call(feed, \"one\") */",
                f"static __attribute__((unused)) void {p}_net_call({p}_state_t *s, int u, const uint8_t *values, int count)", "{",
                "    bool ok = tlg_net_call(&NET, u, values, count);",
                f'    {say}"call %s: %s", NET_CALLS[u], ok ? "sent" : "not sent (too many messages waiting)");',
                "}", ""]
    if mb.serves:
        replies = []
        for c in mb.serves:
            out.append(f"static const char *const R_{c.name.upper()}[] = {{ "
                       + ", ".join(f'"{r}"' for r in c.replies) + " };")
            replies.append(f"R_{c.name.upper()}")
        out += [f"static const char *const *const NET_REPLIES[] = {{ {', '.join(replies)} }};",
                f"static const char *const NET_SERVED_NAMES[] = {{ {', '.join(chr(34) + c.name + chr(34) for c in mb.serves)} }};",
                "/* a tool answers this run's request: mailbox.reply(feed, \"done\") */",
                f"static __attribute__((unused)) void {p}_net_reply({p}_state_t *s, int c, int reply)", "{",
                "    bool ok = tlg_net_reply(&NET, c, (uint8_t)reply);",
                f'    {say}"reply %s: %s%s", NET_SERVED_NAMES[c], NET_REPLIES[c][reply], ok ? "" : " (nothing was asked)");',
                "}", ""]
    return out


def _c_val(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    return str(v)


def _tables(conv, where):
    out = []
    for (tname, field), (cname, vals) in conv.tables.items():
        if where not in conv.table_users.get((tname, field), ()):
            continue
        f = conv.fields[field]
        out.append(f"static const int32_t {cname}[] = {{ {', '.join(map(str, vals))} }};   "
                   f"/* {tname}[{', '.join(f.values)}] */")
    return out + ([""] if out else [])


_HELPERS = """/* Python's // and % round toward minus infinity; C's toward zero. */
static inline int32_t tlg_floordiv(int32_t a, int32_t b) { int32_t q = a / b; return (a % b != 0 && ((a < 0) != (b < 0))) ? q - 1 : q; }
static inline int32_t tlg_mod(int32_t a, int32_t b) { int32_t r = a % b; return (r != 0 && ((r < 0) != (b < 0))) ? r + b : r; }
static inline int32_t tlg_min(int32_t a, int32_t b) { return a < b ? a : b; }
static inline int32_t tlg_max(int32_t a, int32_t b) { return a > b ? a : b; }
static inline int32_t tlg_abs(int32_t a) { return a < 0 ? -a : a; }
"""


def _prebuilt_route(fn, mapping, src, p, node_id):
    if fn.kind == "after_verify":
        body = [f"    if (s->agent.verdict == TLG_VERIFY_OK) return {node_id(mapping['act'])};",
                f"    if (s->agent.verdict == TLG_VERIFY_NEEDS_APPROVAL) return {node_id(mapping['ask'])};",
                f"    return {node_id(mapping['plan'])};"]
    else:
        body = [f"    return s->agent.approved ? {node_id(mapping['verify'])} : {node_id(mapping['plan'])};"]
    return "\n".join([f"/* prebuilt.{fn.kind} */", f"static int route_{src}(const void *st)", "{",
                      f"    const {p}_state_t *s = st;"] + body + ["}", ""])


def _prebuilt_nodes(app, P, p, st):
    """The prebuilt nodes: the same steps as graph.py's _node_* methods, in C."""
    n_in = st.inputs()
    n_th = st.thinks()
    fmt_in = " ".join(f"{f.name}=%s" for f in n_in)
    args_in = ", ".join(f"V_{f.name.upper()}[s->in.{f.name}]" for f in n_in)
    fmt_th = " ".join(f"{f.name}=%s" for f in n_th)
    args_th = ", ".join(f"V_{f.name.upper()}[s->th.{f.name}]" for f in n_th)
