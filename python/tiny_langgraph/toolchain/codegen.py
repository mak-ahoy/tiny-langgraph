"""Generate <name>_schema.h / .c from a schema: tokens, slots, facts, actions, encode/decode."""
from __future__ import annotations

import os

from .planner import domain_of
from .schema import Schema


def _c_ident(s: str) -> str:
    return s.upper().replace("<", "").replace(">", "")


class _Names:
    def __init__(self, schema: Schema):
        self.s = schema
        self.P = schema.name.upper()
        self.p = schema.name

    def tok(self, token: str) -> str:
        return f"{self.P}_TOK_{_c_ident(token)}"

    def val(self, slot: str, value: str) -> str:
        return f"{self.P}_{slot.upper()}_{value.upper()}"

    def fact(self, f: str) -> str:
        return f"{self.P}_FACT_{f.upper()}"

    def out(self, o: str) -> str:
        return f"{self.P}_OUT_{o.upper()}"

    def act(self, a: str) -> str:
        return f"{self.P}_ACT_{a.upper()}"


def _expr_c(node, n: _Names, where: dict[str, str]) -> str:
    kind = node[0]
    if kind == "const":
        return "true" if node[1] else "false"
    if kind in ("eq", "ne"):
        op = "==" if kind == "eq" else "!="
        return f"({where[node[1]]}->{node[1]} {op} {n.val(node[1], node[2])})"
    if kind == "in":
        parts = [f"{where[node[1]]}->{node[1]} == {n.val(node[1], v)}" for v in node[2]]
        return "(" + " || ".join(parts) + ")"
    if kind == "fact":
        return f"fact_{node[1]}(in, th)"
    if kind == "cmp":
        return f"(score_{node[1]}(in, th) {node[2]} {node[3]})"
    if kind == "not":
        return f"(!{_expr_c(node[1], n, where)})"
    if kind in ("and", "or"):
        op = " && " if kind == "and" else " || "
        return "(" + op.join(_expr_c(p, n, where) for p in node[1]) + ")"
    raise ValueError(kind)


def _paren(s: str) -> str:
    """s in one pair of parentheses, for if (...)."""
    if s.startswith("(") and s.endswith(")"):
        depth = 0
        for i, ch in enumerate(s):
            depth += ch == "("
            depth -= ch == ")"
            if depth == 0:
                if i == len(s) - 1:
                    return s
                break
    return f"({s})"


def _comment(text: str) -> str:
    return " ".join(text.split()).replace("*/", "* /")


def generate(schema: Schema, out_dir: str, source: str = "schema.yaml",
             fact_call=None, extra_h: list[str] | None = None) -> list[str]:
    """fact_call(name) -> C expression: use conditions defined elsewhere (the Python API
    converts them from your functions); extra_h: more declarations for the header."""
    os.makedirs(out_dir, exist_ok=True)
    n = _Names(schema)
    d = domain_of(schema)
    P, p = n.P, n.p
    guard = f"{P}_SCHEMA_H"
    banner = f"/* Generated by tiny-langgraph from {source}. Do not edit: change the schema and regenerate. */\n"

    h = [banner, f"#ifndef {guard}", f"#define {guard}", "",
         "#include <stdbool.h>", "#include <stdint.h>", '#include "tlg_plan.h"', "",
         '#ifdef __cplusplus\nextern "C" {\n#endif', ""]
    if schema.description:
        h.append(f"/* {schema.name}: {schema.description} */\n")

    h += [f"#define {P}_N_TOKENS    {len(schema.tokens)}",
          f"#define {P}_SEQ_LEN     {schema.seq_len}",
          f"#define {P}_PROMPT_LEN  {schema.prompt_len}   /* <bos> + inputs + <think> */",
          f"#define {P}_N_FACTS     {len(schema.facts)}",
          f"#define {P}_N_OUTCOMES  {len(schema.outcomes)}",
          f"#define {P}_N_ACTIONS   {len(schema.actions)}",
          f"#define {P}_N_SITUATIONS {schema.situation_count()}u   /* every combination of inputs */",
          f"#define {P}_HAS_RULES   {1 if schema.has_rules else 0}",
          ""]

    h.append("/* ---- tokens (ids are baked into the trained model: never reorder by hand) ---- */")
    h.append("enum {")
    for i, t in enumerate(schema.tokens):
        h.append(f"    {n.tok(t)} = {i},")
    h += ["};", ""]

    for section, slots in (("inputs: what the agent observes", schema.inputs),
                           ("think: what the model concludes", schema.think)):
        h.append(f"/* ---- {section} ---- */")
        for s in slots:
            vals = ", ".join(n.val(s.name, v) for v in s.values)
            h.append(f"enum {{ {vals}, {P}_{s.name.upper()}_COUNT }};")
        h.append("")
    h.append("typedef struct {")
    h += [f"    uint8_t {s.name};" for s in schema.inputs]
    h += [f"}} {p}_inputs_t;", "", "typedef struct {"]
    h += [f"    uint8_t {s.name};" for s in schema.think]
    if not schema.think:
        h.append("    uint8_t none_;      /* no Think fields: ISO C needs at least one member */")
    h += [f"}} {p}_think_t;", ""]

    h.append("/* ---- facts, outcomes, actions ---- */")
    h.append("enum { " + ", ".join(n.fact(f) for f in schema.facts) + " };") if schema.facts else None
    h.append("enum { " + ", ".join(n.out(o.name) for o in schema.outcomes) + " };")
    h.append("enum { " + ", ".join(n.act(a.name) for a in schema.actions) + " };")
    h.append(f"#define {P}_OUT(o)  (1u << {P}_OUT_##o)")
    h.append(f"#define {P}_FACT(f) (1u << {P}_FACT_##f)")
    h.append("")

    h += [f"extern const char *const {p}_token_names[{P}_N_TOKENS];",
          f"extern const tlg_domain_t {p}_domain;", ""]
    for s in schema.inputs + schema.think:
        if s.bins:
            h.append(f"/* {s.name}: turn a measurement into a value using bins {s.bins} */")
            h.append(f"uint8_t  {p}_bin_{s.name}(float x);")
    h += [
        "",
        "/* <bos> + one token per input + <think>. Returns the length, or -1 if a value is out of range. */",
        f"int      {p}_encode(const {p}_inputs_t *in, uint8_t *tokens, int max_tokens);",
        "",
        "/* Bitmask of the facts that hold for these inputs and this assessment. */",
        f"uint32_t {p}_facts(const {p}_inputs_t *in, const {p}_think_t *th);",
        "",
        "/* Situation number index (0 .. N_SITUATIONS-1) as inputs, first slot changing slowest.",
        "   Handy for testing every case. Returns false if index is out of range. */",
        f"bool     {p}_situation(uint32_t index, {p}_inputs_t *in);",
        "",
        *([
            "/* The rules from the schema: the device's own assessment, which the verifier trusts",
            "   instead of the model. Training data is labeled with exactly these rules. */",
            f"void     {p}_think(const {p}_inputs_t *in, {p}_think_t *th);",
            "",
            "/* Bitmask of the outcomes the rules want, e.g. " + f"{P}_OUT({schema.outcomes[0].name.upper()}). */",
            f"uint32_t {p}_want(const {p}_inputs_t *in, const {p}_think_t *th);",
            "",
        ] if schema.has_rules else []),
        "/* Parse the model's answer (the tokens after <think>): think tokens, <plan>, actions, <eos>.",
        "   Returns the plan length, or -1 if the answer is malformed. th may be NULL. */",
        f"int      {p}_decode(const uint8_t *out, int n, {p}_think_t *th, uint8_t *plan, int max_plan);",
        "",
        *(extra_h or []),
        '#ifdef __cplusplus\n}\n#endif',
        "", f"#endif /* {guard} */", ""]

    # ---------------- source ----------------
    c = [banner, f'#include "{p}_schema.h"', "#include <stddef.h>", ""]
    c.append(f"const char *const {p}_token_names[{P}_N_TOKENS] = {{")
    for t in schema.tokens:
        c.append(f'    "{t}",')
    c += ["};", ""]

    c.append(f"static const char *const OUTCOME_NAMES[] = {{ " +
             ", ".join(f'"{o.name}"' for o in schema.outcomes) + " };")
    c.append(f"static const uint8_t OUTCOME_WEIGHTS[] = {{ " +
             ", ".join(str(o.weight) for o in schema.outcomes) + " };")
    if schema.facts:
        c.append(f"static const char *const FACT_NAMES[] = {{ " +
                 ", ".join(f'"{f}"' for f in schema.facts) + " };")
    c.append("")
    c.append("static const tlg_action_t ACTIONS[] = {")
    c.append("    /* name, needs (facts), after (outcomes), achieves (outcomes), cost, approval */")
    for i, a in enumerate(schema.actions):
        c.append(f'    {{ "{a.name}", 0x{d.needs[i]:x}u, 0x{d.after[i]:x}u, 0x{d.achieves[i]:x}u, '
                 f'{a.cost}, {"true" if a.approval else "false"} }},')
    c += ["};", ""]
    c += [f"const tlg_domain_t {p}_domain = {{",
          "    .actions = ACTIONS,",
          f"    .n_actions = {P}_N_ACTIONS,",
          "    .outcome_names = OUTCOME_NAMES,",
          "    .outcome_weights = OUTCOME_WEIGHTS,",
          f"    .n_outcomes = {P}_N_OUTCOMES,",
          f"    .fact_names = {'FACT_NAMES' if schema.facts else 'NULL'},",
          f"    .n_facts = {P}_N_FACTS,",
          f"    .only_if_wanted = 0x{d.only_if_wanted:x}u,",
          f"    .budget = {schema.budget},",
          "};", ""]

    for s in schema.inputs + schema.think:
        if s.bins:
            c.append(f"uint8_t {p}_bin_{s.name}(float x)\n{{")
            for i, b in enumerate(s.bins):
                c.append(f"    if (x < {b!r}f) return {n.val(s.name, s.values[i])};")
            c.append(f"    return {n.val(s.name, s.values[-1])};\n}}\n")

    c.append(f"int {p}_encode(const {p}_inputs_t *in, uint8_t *t, int max)\n{{")
    c.append(f"    if (max < {P}_PROMPT_LEN) return -1;")
    for s in schema.inputs:
        c.append(f"    if (in->{s.name} >= {P}_{s.name.upper()}_COUNT) return -1;")
    c.append("    int k = 0;")
    c.append(f"    t[k++] = {n.tok('<bos>')};")
    for s in schema.inputs:
        c.append(f"    t[k++] = (uint8_t)({n.tok(s.token(s.values[0]))} + in->{s.name});")
    c.append(f"    t[k++] = {n.tok('<think>')};")
    c += ["    return k;", "}", ""]

    where = {s.name: "in" for s in schema.inputs}
    where.update({s.name: "th" for s in schema.think})
    sig = f"(const {p}_inputs_t *in, const {p}_think_t *th)"

    # scores and facts as small helpers, in dependency order
    for kind, name in schema.order:
        if kind == "score":
            sc = schema.scores[name]
            c.append(f"/* score {name} */")
            for slot, pts in sc.points.items():
                vals = schema.inputs + schema.think
                values = next(s for s in vals if s.name == slot).values
                c.append(f"static const int16_t SCORE_{name.upper()}_{slot.upper()}[] = {{ "
                         + ", ".join(str(pts.get(v, 0)) for v in values) + " };   /* "
                         + ", ".join(values) + " */")
            c.append(f"static inline int score_{name}{sig}\n{{")
            c.append("    (void)in; (void)th;")
            terms = " + ".join(f"SCORE_{name.upper()}_{slot.upper()}[{where[slot]}->{slot}]" for slot in sc.points)
            c += [f"    return {terms};", "}", ""]
        elif kind == "fact":
            c.append(f"/* {name}: {_comment(schema.fact_text[name])} */")
            c.append(f"static inline bool fact_{name}{sig}\n{{")
            c.append("    (void)in; (void)th;")
            c += [f"    return {_expr_c(schema.facts[name], n, where)};", "}", ""]

    c.append(f"uint32_t {p}_facts{sig}\n{{")
    c.append("    (void)in; (void)th;\n    uint32_t f = 0;")
    for fname in schema.facts:
        call = fact_call(fname) if fact_call else f"fact_{fname}(in, th)"
        c.append(f"    if ({call}) f |= 1u << {n.fact(fname)};")
    c += ["    return f;", "}", ""]

    if schema.has_rules:
        c.append(f"void {p}_think(const {p}_inputs_t *in, {p}_think_t *th)\n{{")
        c.append(f"    {p}_think_t zero = {{0}};\n    *th = zero;")
        for kind, slot in schema.order:
            if kind != "think":
                continue
            c.append(f"    /* {slot}: first matching rule wins */")
            rules = schema.think_rules[slot]
            for i, (value, cond, text) in enumerate(rules):
                assign = f"th->{slot} = {n.val(slot, value)};"
                if i == len(rules) - 1:
                    c.append(f"    else {assign}" if i else f"    {assign}")
                else:
                    kw = "if" if i == 0 else "else if"
                    c.append(f"    {kw} {_paren(_expr_c(cond, n, where))}   /* {_comment(text)} */")
                    c.append(f"        {assign}")
        c += ["}", ""]

        c.append(f"uint32_t {p}_want{sig}\n{{")
        c.append("    (void)in; (void)th;\n    uint32_t w = 0;")
        for o in schema.outcomes:
            if o.name not in schema.want_rules:
                continue
            cond, text = schema.want_rules[o.name]
            c.append(f"    /* {o.name}: {_comment(text)} */")
            if cond == ("const", True):
                c.append(f"    w |= {P}_OUT({o.name.upper()});")
            elif cond != ("const", False):
                c.append(f"    if {_paren(_expr_c(cond, n, where))} w |= {P}_OUT({o.name.upper()});")
        c += ["    return w;", "}", ""]

    c.append(f"bool {p}_situation(uint32_t index, {p}_inputs_t *in)\n{{")
    c.append(f"    if (index >= {P}_N_SITUATIONS) return false;")
    for s in reversed(schema.inputs):
        cnt = f"{P}_{s.name.upper()}_COUNT"
        c.append(f"    in->{s.name} = (uint8_t)(index % {cnt}); index /= {cnt};")
    c += ["    return true;", "}", ""]

    first_act = n.tok(schema.actions[0].name)
    last_act = n.tok(schema.actions[-1].name)
    c.append(f"int {p}_decode(const uint8_t *out, int n, {p}_think_t *th, uint8_t *plan, int max_plan)\n{{")
    c.append("    int i = 0;")
    if not schema.think:
        c.append("    (void)th;")
    for s in schema.think:
        base = n.tok(s.token(s.values[0]))
        c.append(f"    if (i >= n || out[i] < {base} || out[i] >= {base} + {P}_{s.name.upper()}_COUNT) return -1;")
        c.append(f"    if (th) th->{s.name} = (uint8_t)(out[i] - {base});")
        c.append("    i++;")
    c.append(f"    if (i >= n || out[i++] != {n.tok('<plan>')}) return -1;")
    c += ["    int len = 0;",
          f"    for (; i < n && out[i] != {n.tok('<eos>')}; i++) {{",
          f"        if (out[i] < {first_act} || out[i] > {last_act} || len >= max_plan) return -1;",
          f"        plan[len++] = (uint8_t)(out[i] - {first_act});",
          "    }",
          f"    if (i >= n) return -1;   /* no <eos> */",
          "    return len;", "}", ""]

    hpath = os.path.join(out_dir, f"{p}_schema.h")
    cpath = os.path.join(out_dir, f"{p}_schema.c")
    with open(hpath, "w", encoding="utf-8") as f:
        f.write("\n".join(x for x in h if x is not None))
    with open(cpath, "w", encoding="utf-8") as f:
        f.write("\n".join(c))
    return [hpath, cpath]
